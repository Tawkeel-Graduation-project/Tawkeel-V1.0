export interface StreamCallbacks {
  onChunk: (accumulatedText: string, latestChunk: string) => void;
  onFinish: (finalText: string, citations: Citation[], hasNoSource?: boolean) => void;
  onError?: (error: Error) => void;
}

/**
 * Simulates a realistic token-by-token Arabic streaming response.
 * Breaks down legal text into natural word clusters and streams at 25ms intervals.
 * Fully cancelable via AbortSignal.
 */
export async function streamLegalResponse(
  query: string,
  callbacks: StreamCallbacks,
  signal?: AbortSignal,
): Promise<void> {
  const trimmed = query.trim().toLowerCase();

  // Simulated error condition (for testing error states)
  if (
    trimmed.includes("فشل الاتصال") ||
    trimmed.includes("خطأ في الشبكة") ||
    trimmed.includes("network_error") ||
    trimmed.includes("network") ||
    trimmed === "error"
  ) {
    await new Promise((resolve) => setTimeout(resolve, 350));
    callbacks.onError?.(new Error("network"));
    return;
  }

  // Simulated out-of-scope / no legal source found condition (PRD §C2)
  if (
    trimmed.includes("بدون مصدر") ||
    trimmed.includes("خارج القانون") ||
    trimmed.includes("لا يوجد مصدر") ||
    trimmed.includes("nosource") ||
    trimmed.includes("notfound")
  ) {
    await new Promise((resolve) => setTimeout(resolve, 400));
    callbacks.onFinish("", [], true);
    return;
  }

  const { content, citations } = findAnswer(query);

  // Divide into natural chunks (1-3 words per chunk)
  const tokens = content.split(/(\s+|\n+)/);
  let accumulated = "";

  // Initial thinking pause (350ms)
  await new Promise((resolve) => setTimeout(resolve, 350));
  if (signal?.aborted) {
    callbacks.onError?.(new Error("aborted"));
    return;
  }

  for (let i = 0; i < tokens.length; i++) {
    if (signal?.aborted) {
      callbacks.onError?.(new Error("aborted"));
      return;
    }

    const token = tokens[i];
    accumulated += token;
    callbacks.onChunk(accumulated, token);

    // Natural pacing variation: punctuation gets a slightly longer pause
    const delay = token.includes("\n") ? 60 : token.includes(".") || token.includes(":") ? 45 : 20;
    await new Promise((resolve) => setTimeout(resolve, delay));
  }

  callbacks.onFinish(accumulated, citations, false);
}
